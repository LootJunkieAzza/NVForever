def quest_state(quest, label, vars_=(), stages=()):
    steps = [num([quest], "GetQuestRunning {0}", label, "running"),
             num([quest], "GetQuestCompleted {0}", label, "completed"),
             num([quest], "GetStage {0}", label, "stage")]
    steps += [num([quest], f"GetStageDone {{0}} {s}", label, f"done.{s}") for s in stages]
    steps += [qvar(quest, v, label) for v in vars_]
    return steps


def trial_doc():
    """Save nvfdoc (Doc Mitchell's house): object-script variables through references,
    GameMode around an activation, GetSecondsPassed across a menu, OnAdd and GameMode
    of an inventory item, an OnActivate that writes another reference's variable. Never
    saved; the last step walks the player out of the house."""
    timers = ([SKULL, VCG00, VMQ03A_TIMER],
              ['{0}.GetVariable "timer"', 'GetVariable "fTimer" {1}', 'GetVariable "fTimer" {2}'])
    steps = []
    steps += quest_state(CONTROL_RUMBLE, "ControlRumble at start", RUMBLE_VARS, (0, 1))
    steps += quest_state(VCG00, "VCG00 at start", ["bRunTimer", "fTimer"], (100,))
    steps += quest_state(VMQ03A_TIMER, "VMQ03aTimer at start", ["bRunTimer", "fTimer", "nEvent"])
    # Reference variables: several spellings, one per step (a failed compile only fails its step).
    steps += [rvar(SKULL, v, "skull at start") for v in ("runTimer", "timer", "grabbed", "released", "SayLater")]
    steps += [rvar(SKULL, "NoSuchVariable", "skull at start")]
    steps += [num([SKULL], 'GetVariable "timer" {0}', "skull spelling", "GetVariable name ref"),
              num([SKULL], "{0}.timer", "skull spelling", "ref.var"),
              num([SKULL], '{0}.HasVariable "timer"', "skull spelling", "HasVariable")]
    steps += [rvar(DOC, "PlayerLeft", "Doc at start")]
    steps += [num([JAR], "player.GetItemCount {0}", "items at start", "jar"),
              num([POWDER], "player.GetItemCount {0}", "items at start", "powder")]
    steps += [num([SKULL], "{0}.GetDisabled", "skull at start", "disabled")]
    # Writes on the skull's script.
    steps += act([SKULL], ['{0}.SetVariable "timer" 100000', '{0}.SetVariable "runTimer" 1'])
    steps += [rvar(SKULL, "timer", "skull after SetVariable"), rvar(SKULL, "runTimer", "skull after SetVariable")]
    steps += sample("skull timer running", [SKULL], ['{0}.GetVariable "timer"'], 40)
    # Activation: read in the activating script, then every loop.
    steps.append(cs.query(script([SKULL], ["{0}.Activate player", 'let fV := {0}.GetVariable "timer"',
                                           "SetFunctionValue fV"]), "skull activation", "timer in the same script"))
    steps += sample("skull timer after activation", [SKULL], ['{0}.GetVariable "timer"'], 40)
    steps += [num([SKULL], "{0}.GetDisabled", "skull after activation", "disabled"), menu(CONTAINER_MENU, "skull after activation")]
    # Quest timers, then a menu gap.
    steps += set_qvar(VCG00, "fTimer", 100000) + set_qvar(VCG00, "bRunTimer", 1)
    steps += set_qvar(VMQ03A_TIMER, "fTimer", 100000) + set_qvar(VMQ03A_TIMER, "bRunTimer", 1)
    steps += act([VCG00], ["StartQuest {0}"]) + act([VMQ03A_TIMER], ["StartQuest {0}"], 60)
    steps += sample("timers before the menu", *timers, 120)
    steps += act([DRESSER], ["{0}.Activate player"], 10)
    steps += [menu(CONTAINER_MENU, "dresser menu open")]
    steps += sample("timers in the menu", *timers, 300)
    steps += [{"console": "CloseAllMenus"}]
    steps += sample("timers after the menu", *timers, 120)
    steps += [menu(CONTAINER_MENU, "after CloseAllMenus")]
    # OnAdd and GameMode of an inventory item.
    steps.append(cs.query(script([JAR, POWDER], ["player.AddItem {0} 1 1",
                                                 'SetFunctionValue (($ player.GetItemCount {0}) + "|" + ($ player.GetItemCount {1}))']),
                          "jar added", "counts in the same script"))
    steps += sample("jar after AddItem", [JAR, POWDER], ["player.GetItemCount {0}", "player.GetItemCount {1}"], 30)
    # The house door: its OnActivate writes Doc's variable, then activates (walks out).
    steps.append(cs.query(script([DOC_DOOR, DOC], ["{0}.Activate player", 'let fV := {1}.GetVariable "PlayerLeft"',
                                                            "SetFunctionValue fV"]), "door activation", "PlayerLeft in the same script"))
    steps += [{"frames": 300}, rvar(DOC, "PlayerLeft", "after the door"),
              cs.query(cs.cell_query("player", (cs.MASTERS, None)), "after the door", "player cell")]
    j = cs.job("q5b_trial_doc", "nvfdoc (Doc Mitchell's house; changes timers, adds an item, leaves the house; never saved).",
               steps, cs.MASTERS)
    j["title"] = "Layer 5 round 2 trial: reference variables, activation, menu gap, OnAdd (about 30 s)"
    return j


def trial_test():
    """Save nvftest: package choice under a mixed AND/OR condition list (Goodsprings
    settlers' flee package), the stray ElseIf of TecMineHostage's OnActivate (a dead
    hostage activated), and ControlRumble's five-entry stage 0. Kills two actors in
    Techatticup Mine (remote); never saved."""
    steps = []
    steps += quest_state(CONTROL_RUMBLE, "ControlRumble at start", RUMBLE_VARS, (0, 1))
    steps += quest_state(VMS16, "VMS16 at start", ["bGunFightStart", "bTrudyHelp"])
    steps += quest_state(VMS16B, "VMS16b at start", ["bPowderGangAttacking"])
    steps += quest_state(VTECHATTICUP, "VTechatticup at start", ["NumHostages", "HostagesDead", "DoOnce"], (110,))
    for r in SETTLERS:
        steps += [package(r, f"settler {r} at start"), num([r], "{0}.GetDisabled", f"settler {r} at start", "disabled"),
                  num([r], "{0}.GetDead", f"settler {r} at start", "dead"),
                  cs.query(cs.cell_query(r, (cs.MASTERS, None)), f"settler {r} at start", "cell")]
    for h in (HOSTAGE_1, LEGIONARY_5):
        steps += [num([h], "{0}.GetDead", f"{h} at start", "dead"), num([h], "{0}.GetDisabled", f"{h} at start", "disabled")]
    steps += [rvar(HOSTAGE_1, "Freed", f"{HOSTAGE_1} at start")]

    def flee_case(name, gunfight, trudy, gang):
        out = set_qvar(VMS16, "bGunFightStart", gunfight) + set_qvar(VMS16, "bTrudyHelp", trudy)
        out += set_qvar(VMS16B, "bPowderGangAttacking", gang)
        out += act(SETTLERS, [f"{{{i}}}.EvaluatePackage" for i in range(len(SETTLERS))], 60)
        out += [package(r, f"{name}: settler {r}") for r in SETTLERS]
        return out

    steps += flee_case("A=1 B=0 C=1 (trudy 0)", 1, 0, 0)
    steps += flee_case("A=1 B=0 C=0 (trudy 1)", 1, 1, 0)
    steps += flee_case("A=0 B=1 C=1", 0, 0, 1)
    steps += flee_case("A=0 B=1 C=0", 0, 1, 1)
    steps += flee_case("A=0 B=0 C=1", 0, 0, 0)

    # A dead actor without OnActivate, then the hostage.
    for name, r in (("legionary", LEGIONARY_5), ("hostage", HOSTAGE_1)):
        steps += act([r], ["{0}.Kill"], 60)
        steps += [num([r], "{0}.GetDead", f"{name} killed", "dead")]
        steps += act([r], ["{0}.Activate player"], 30)
        steps += [menu(CONTAINER_MENU, f"{name} activated"), menu(MESSAGE_MENU, f"{name} activated"),
                  num([], "MenuMode", f"{name} activated", "menu.any")]
        steps += [{"console": "CloseAllMenus"}, {"frames": 30}, num([], "MenuMode", f"{name} after CloseAllMenus", "menu.any")]
    steps += quest_state(VTECHATTICUP, "VTechatticup after the deaths", ["NumHostages", "HostagesDead", "DoOnce"], (110,))

    # ControlRumble stage 0: five entries without conditions.
    for v in ("Stage1Fired", "Stage1FireOnTimerValue", "stage1RumbleLeft", "Stage1Duration", "timerMaxValue"):
        steps += set_qvar(CONTROL_RUMBLE, v, 7)
    steps += quest_state(CONTROL_RUMBLE, "ControlRumble before stage 0", RUMBLE_VARS, (0, 1))
    steps += act([CONTROL_RUMBLE], ["SetStage {0} 0"], cs.SETTLE_FRAMES_LONG)
    steps += quest_state(CONTROL_RUMBLE, "ControlRumble after stage 0", RUMBLE_VARS, (0, 1))
    j = cs.job("q5b_trial_test", "nvftest (changes VMS16/VMS16b variables, kills two actors in Techatticup Mine, "
               "sets ControlRumble stage 0; never saved).", steps, cs.MASTERS)
    j["title"] = "Layer 5 round 2 trial: condition grouping, stray ElseIf, multi-entry stage (about 20 s)"
    return j


