    steps += sample("timers before the menu", *timers, 60)
    steps += [clock("clock before the menu"), {"screenshot": "before_menu"}]
    steps += act([DRESSER], ["{0}.Activate player"], 30) + [menu(CONTAINER_MENU, "dresser menu open")]
    steps += sample("timers in the menu", *timers, 1500)
    steps += [clock("clock before CloseAllMenus"), {"screenshot": "before_close"}, {"console": "CloseAllMenus"}]
    steps += sample("timers after the menu", *timers, 60)
