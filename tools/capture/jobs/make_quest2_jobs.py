def trial_doc3():
    """Save nvfdoc: OnActivate run by a scripted Activate with the flag (skull: empty
    block; the house door: writes Doc's PlayerLeft, then activates), a long container
    menu and a loading screen timed by screenshot file names (unix seconds)."""
