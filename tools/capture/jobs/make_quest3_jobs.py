#!/usr/bin/env python3
"""Writes the diagnostic jobs of the third round of Layer 5 captures (workstream 5C,
docs/spec-notes/layer5-captures.md section 9) into this folder. Scenario jobs are
generated by capture_quests.py from parity-lab/inputs/layer5/; these jobs only find
out what can be observed and how.

  python tools/capture/jobs/make_quest3_jobs.py

Forms (FalloutNV.esm FormIDs, looked up read-only 2026-10-09 with `fnvtool esm
inventory` / `esm decode`; no game data is stored here):
- reputations (REPU, DATA value in brackets): RepNVPowderGanger 0x001558E6 (30),
  RepNVFreeside 0x00129A7A (70), RepNVNovac 0x00129A79 (20), RepNVFollowers 0x00124AD1
  (50), RepNVBrotherhood 0x0011E662 (20), RepNVGreatKhans 0x0011989B (30), RepNVTheStrip
  0x00118F61 (40), RepNVWhiteGloveSociety 0x00116F16 (10), RepNVGoodsprings 0x00104C22
  (15), RepNVBoomer 0x000FFAE8 (50), RepNVNCR 0x000F43DE (80), RepNVCaesarsLegion
  0x000F43DD (100), RepNVPrimm 0x000F2406 (30);
- aid items: NVCateye 0x0007EA1B (CateyeBaseEffect, script 0x0007EA20: Start sets the
  player's Nighteye to 1, Finish to 0; 120 s), NukaCola 0x0001519E (NukaColaAddCap,
  script 0x0004E6A3: Start adds one cap; no duration), NVContrerasMedicalSupplies
  0x000F1865 (RestoreAllLimbs, script 0x000CB07F: Start, Update and Finish each restore
  the six limb conditions; duration 0); Caps001 0x0000000F;
- the ability ImplantRegenBoost 0x0014CCE2 (ImplantRegenScript 0x0014CCE3: each
  ScriptEffectUpdate restores ScriptEffectElapsedSeconds / 10 health);
- quests VCG00 0x00102037 (a GetSecondsPassed countdown every frame, used as a clock),
  BeatrixFX 0x0017BA11 (adds one game hour about 9 s after it starts);
- references: Doc Mitchell's dresser 0x00103E37; two Goodsprings windows 0x001771EB,
  0x001771EA (WastelandWindowScript 0x001759FC: GameMode copies GetCurrentTime into
  `Time` every run).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
sys.path.insert(0, HERE)

import capture_steps as cs  # noqa: E402
from make_quest2_jobs import act, menu, num, qvar, sample, script, set_qvar  # noqa: E402

REPS = {"PowderGanger": ("0x001558E6", 30), "Freeside": ("0x00129A7A", 70), "Novac": ("0x00129A79", 20),
        "Followers": ("0x00124AD1", 50), "Brotherhood": ("0x0011E662", 20), "GreatKhans": ("0x0011989B", 30),
        "TheStrip": ("0x00118F61", 40), "WhiteGlove": ("0x00116F16", 10), "Goodsprings": ("0x00104C22", 15),
        "Boomer": ("0x000FFAE8", 50), "NCR": ("0x000F43DE", 80), "Legion": ("0x000F43DD", 100),
        "Primm": ("0x000F2406", 30)}
# Reputations no quest script watches in GameMode and whose members are far from the
# capture saves (searched in the masters' script sources); the only ones a job changes.
SAFE = ("WhiteGlove", "Novac", "GreatKhans", "Followers", "Freeside")

CATEYE = "0x0007EA1B"
NUKA_COLA = "0x0001519E"
CONTRERAS = "0x000F1865"
CAPS = "0x0000000F"
REGEN = "0x0014CCE2"
VCG00 = "0x00102037"
BEATRIX_FX = "0x0017BA11"
DRESSER = "0x00103E37"
WINDOWS = ["0x001771EB", "0x001771EA"]
CONTAINER_MENU = 1008

# Reads of one reputation (ref variable {0}): name -> expression.
REP_READS = {"fame": "GetReputation {0} 1", "infamy": "GetReputation {0} 0",
             "pct.fame": "GetReputationPct {0} 1", "pct.infamy": "GetReputationPct {0} 0",
             "threshold.0": "GetReputationThreshold {0} 0", "threshold.1": "GetReputationThreshold {0} 1",
             "threshold.2": "GetReputationThreshold {0} 2"}
ALL_READS = " + \"|\" + ".join(f"($ ({e}))" for e in REP_READS.values())


def rep_state(rep, label):
    return [num([rep], e, label, f) for f, e in REP_READS.items()]


def rep_line(rep, label, field, before=()):
    """Statements `before`, then every read of the reputation in the same script, as
    'fame|infamy|pct fame|pct infamy|t0|t1|t2'."""
    return cs.query(script([rep], list(before) + [f"SetFunctionValue ({ALL_READS})"]), label, field)


def boundaries(rep, scale, axis, label):
    """In one script: the axis swept from 0 to 1.2 x scale in steps of scale/1000 (the
    other axis 0); returns the first value of each run of equal threshold codes
    (100 t0 + 10 t1 + t2) as 'value:code' pairs (at most 10)."""
    other = 1 - axis
    step = scale / 1000
    lines = [f"SetReputation {{0}} {other} 0", "let fK := 0", "let fX := 0", "let fPrev := -1", "let fN := 0"]
    lines += [f"let b{k} := -1" for k in range(10)] + [f"let c{k} := -1" for k in range(10)]
    lines += [f"while fX <= {cs.number(scale * 1.2)}",
              f"  SetReputation {{0}} {axis} fX",
              "  let fT := (GetReputationThreshold {0} 0) * 100 + (GetReputationThreshold {0} 1) * 10 + (GetReputationThreshold {0} 2)",
              "  if fT != fPrev"]
    for k in range(10):
        lines += [f"    {'if' if k == 0 else 'elseif'} fN == {k}", f"      let b{k} := fX", f"      let c{k} := fT"]
    lines += ["    endif", "    let fN := fN + 1", "    let fPrev := fT", "  endif",
              "  let fK := fK + 1", f"  let fX := fK * {cs.number(step)}", "loop", f"SetReputation {{0}} {axis} 0"]
    out = " + \"|\" + ".join(f"($ b{k}) + \":\" + ($ c{k})" for k in range(10))
    lines += [f"SetFunctionValue ({out})"]
    decls = ["float fK", "float fX", "float fPrev", "float fN", "float fT"] + [f"float b{k}" for k in range(10)] + \
            [f"float c{k}" for k in range(10)]
    return cs.query(script([rep], lines, decls), label, f"boundaries axis {axis}")


def grid_row(rep, scale, fame_frac, label):
    """Fame at fame_frac x scale, infamy swept over 0, 0.05, ... 1.0 x scale; the
    threshold codes as text."""
    fracs = [k / 20 for k in range(21)]
    lines = [f"SetReputation {{0}} 1 {cs.number(round(fame_frac * scale, 6))}"]
    parts = []
    for k, f in enumerate(fracs):
        lines += [f"SetReputation {{0}} 0 {cs.number(round(f * scale, 6))}",
                  f"let t{k} := (GetReputationThreshold {{0}} 0) * 100 + (GetReputationThreshold {{0}} 1) * 10 + (GetReputationThreshold {{0}} 2)"]
        parts.append(f"($ t{k})")
    lines += ["SetReputation {0} 1 0", "SetReputation {0} 0 0", "SetFunctionValue (" + " + \"|\" + ".join(parts) + ")"]
    return cs.query(script([rep], lines, [f"float t{k}" for k in range(21)]), label, f"fame {fame_frac:.2f}")


def trial_rep():
    """Save nvfdoc: every reputation's state; whether the functions compile with a
    reputation in a ref variable; AddReputation / RemoveReputation per deed size on two
    reputations of different scale; SetReputation edges; threshold boundaries per axis
    and a 21 x 21 fame/infamy grid of threshold codes on five reputations. Only the five
    SAFE reputations are changed; each is set back to 0/0 at the end. Never saved."""
    steps = []
    for name, (fid, _) in REPS.items():
        steps += rep_state(fid, f"{name} at start")
    steps += [num([], 'GetNumericGameSetting "fReputationBumpVeryMinor"', "gmst", "fReputationBumpVeryMinor"),
              num([], 'GetGameSetting "fReputationBumpVeryMinor"', "gmst", "GetGameSetting VeryMinor")]
    for g in ("Minor", "Average", "Major", "VeryMajor"):
        steps.append(num([], f'GetNumericGameSetting "fReputationBump{g}"', "gmst", f"fReputationBump{g}"))
    # GetReputation inside an if (the wiki says it reads reliably only there).
    gs = REPS["Goodsprings"][0]
    steps.append(cs.query(script([gs], ["let fV := -1", "if GetReputation {0} 1 > 0", "  let fV := 1", "else",
                                        "  let fV := 0", "endif", "SetFunctionValue fV"]), "Goodsprings at start", "fame > 0 (if)"))

    # Deed sizes: AddReputation axis a size k from 0/0; RemoveReputation from 20.
    for name in ("WhiteGlove", "Freeside"):
        fid, scale = REPS[name]
        for axis in (1, 0):
            for k in range(1, 6):
                steps += act([fid], ["SetReputation {0} 1 0", "SetReputation {0} 0 0"], 2)
                steps += act([fid], [f"AddReputation {{0}} {axis} {k}"], 10)
                steps += [rep_line(fid, f"{name} add axis {axis} size {k}", "after")]
            for k in range(1, 6):
                steps += act([fid], ["SetReputation {0} 1 0", "SetReputation {0} 0 0", f"SetReputation {{0}} {axis} 20"], 2)
                steps += act([fid], [f"RemoveReputation {{0}} {axis} {k}"], 10)
                steps += [rep_line(fid, f"{name} remove axis {axis} size {k} from 20", "after")]
        # Edges: past the scale, negative, fractional, sizes 0 and 6, removal below 0.
        edges = [("add 5 at scale-1", [f"SetReputation {{0}} 1 {scale - 1}", "AddReputation {0} 1 5"]),
                 ("set 2 x scale", [f"SetReputation {{0}} 1 {2 * scale}"]),
                 ("set -3", ["SetReputation {0} 1 -3"]),
                 ("set 2.5", ["SetReputation {0} 1 2.5"]),
                 ("add size 0", ["SetReputation {0} 1 0", "AddReputation {0} 1 0"]),
                 ("add size 6", ["SetReputation {0} 1 0", "AddReputation {0} 1 6"]),
                 ("remove 5 from 1", ["SetReputation {0} 1 1", "RemoveReputation {0} 1 5"]),
                 ("add -2", ["SetReputation {0} 1 10", "AddReputation {0} 1 -2"])]
        for elabel, lines in edges:
            steps += act([fid], ["SetReputation {0} 1 0", "SetReputation {0} 0 0"] + lines, 10)
            steps += [rep_line(fid, f"{name} {elabel}", "after")]
        steps += act([fid], ["SetReputation {0} 1 0", "SetReputation {0} 0 0"], 2)

    # The same script versus the next frame.
    fid, scale = REPS["Novac"]
    for v in (3, 5, 10, 15):
        steps.append(rep_line(fid, f"Novac fame {v}", "same script", [f"SetReputation {{0}} 1 {v}", "SetReputation {0} 0 0"]))
        steps += [{"frames": 2}, rep_line(fid, f"Novac fame {v}", "next frames")]

    # Boundaries per axis and the grid.
    for name in SAFE:
        fid, scale = REPS[name]
        steps += act([fid], ["SetReputation {0} 1 0", "SetReputation {0} 0 0"], 2)
        steps += [boundaries(fid, scale, 1, f"{name} boundaries"), boundaries(fid, scale, 0, f"{name} boundaries")]
        steps += [grid_row(fid, scale, k / 20, f"{name} grid") for k in range(21)]
        steps += act([fid], ["SetReputation {0} 1 0", "SetReputation {0} 0 0"], 2)
        steps += rep_state(fid, f"{name} at the end")
    j = cs.job("q5c_trial_rep", "nvfdoc (changes five reputations no script watches and sets them back to 0; never saved).",
               steps, cs.MASTERS)
    j["title"] = "Layer 5 round 3 trial: reputation functions (about 1 min)"
    return j


def ticks():
    """VCG00's countdown from 100000 as whole 1/64 s ticks (ref variable {0} = VCG00)."""
    return '(100000 - (GetVariable "fTimer" {0})) * 64'


def clock_start():
    """VCG00 as a clock: its GameMode counts fTimer down by GetSecondsPassed every frame
    (delay 0.01; docs/spec-notes/layer5-captures.md section 5.4)."""
    return (set_qvar(VCG00, "fTimer", 100000) + set_qvar(VCG00, "bRunTimer", 1)
            + act([VCG00], ["StartQuest {0}"], 60))


def clock(label, field="ticks"):
    return num([VCG00], ticks(), label, field)


def until_av(av, value, max_frames, op="=="):
    body = ["let fV := 0", f"if player.GetAV {av} {op} {value}", "  let fV := 1", "endif", "SetFunctionValue fV"]
    return {"until": cs.function(["float fV"], body), "max_frames": max_frames}


def trial_fx():
    """Save nvfdoc: effect scripts of aid items. Cateye (120 s): Start inside EquipItem?
    Finish when (VCG00 clock, game clock, screenshots for real time)? With a container
    menu held open during the effect; with a second Cateye taken while the first is
    active. Nuka-Cola (no duration): Start inside EquipItem. Contreras' supplies
    (duration 0): in which frames Start/Update/Finish restore a limb. The regeneration
    ability: ScriptEffectUpdate per frame and ScriptEffectElapsedSeconds. Never saved."""
    steps = clock_start()
    steps += [clock("clock at start"), num([], "GameDaysPassed", "clock at start", "GameDaysPassed")]
    steps += [num([], "player.GetAV Nighteye", "player at start", "Nighteye"),
              num([CATEYE], "player.GetItemCount {0}", "player at start", "cateye"),
              num([NUKA_COLA], "player.GetItemCount {0}", "player at start", "nuka cola"),
              num([CONTRERAS], "player.GetItemCount {0}", "player at start", "contreras"),
              num([CAPS], "player.GetItemCount {0}", "player at start", "caps"),
              num([], "player.GetAV PerceptionCondition", "player at start", "PerceptionCondition"),
              num([], "player.GetAV Health", "player at start", "Health"),
              num([], "player.GetBaseAV Health", "player at start", "base Health")]
    steps += act([CATEYE, NUKA_COLA, CONTRERAS], ["player.AddItem {0} 3 1", "player.AddItem {1} 2 1", "player.AddItem {2} 2 1"], 30)

    # Nuka-Cola: Start inside the call?
    steps.append(cs.query(script([NUKA_COLA, CAPS], ["let fA := player.GetItemCount {1}", "player.EquipItem {0} 0 1",
                                                     'SetFunctionValue (($ fA) + "|" + ($ player.GetItemCount {1}) + "|" + ($ player.GetItemCount {0}))'],
                                 ("float fA",)), "nuka cola used", "caps before|caps after|colas in the same script"))
    steps += sample("nuka cola caps|colas", [CAPS, NUKA_COLA], ["player.GetItemCount {0}", "player.GetItemCount {1}"], 30)

    # Contreras' supplies: damage, use, damage again in the same script; then each
    # frame read and damage by 5 (100 = restored since the last frame).
    steps += act([], ["player.DamageAV PerceptionCondition 40"], 10)
    steps += [num([], "player.GetAV PerceptionCondition", "limb before supplies", "PerceptionCondition")]
    steps.append(cs.query(script([CONTRERAS], ["let fA := player.GetAV PerceptionCondition", "player.EquipItem {0} 0 1",
                                               "let fB := player.GetAV PerceptionCondition",
                                               "player.DamageAV PerceptionCondition 20",
                                               'SetFunctionValue (($ fA) + "|" + ($ fB) + "|" + ($ player.GetAV PerceptionCondition) + "|" + ($ player.GetItemCount {0}))'],
                                 ("float fA", "float fB")), "supplies used", "before|after use|after damage|count"))
    probe = script([], ["let fV := player.GetAV PerceptionCondition", "player.DamageAV PerceptionCondition 5",
                        "SetFunctionValue fV"])
    steps += [cs.query(probe, "sample:limb after supplies", str(k)) for k in range(20)]
    steps += act([], ["player.RestoreAV PerceptionCondition 100"], 10)

    # The regeneration ability: health per frame before, with and after it.
    steps += act([], ["player.DamageAV Health 40"], 10)
    steps += sample("regen off health|ticks", [VCG00], ["(player.GetAV Health) * 1000", ticks()], 40)
    steps += act([REGEN], ["player.AddSpell {0}"], 0)
    steps += sample("regen on health|ticks", [VCG00], ["(player.GetAV Health) * 1000", ticks()], 120)
    steps += act([DRESSER], ["{0}.Activate player"], 1) + [menu(CONTAINER_MENU, "regen menu open")]
    steps += sample("regen in menu health|ticks", [VCG00], ["(player.GetAV Health) * 1000", ticks()], 120)
    steps += [{"console": "CloseAllMenus"}]
    steps += sample("regen after menu health|ticks", [VCG00], ["(player.GetAV Health) * 1000", ticks()], 60)
    steps += act([REGEN], ["player.RemoveSpell {0}"], 0)
    steps += sample("regen removed health|ticks", [VCG00], ["(player.GetAV Health) * 1000", ticks()], 40)

    # Cateye 1: Start inside the call; Finish at the end of the duration.
    steps.append(cs.query(script([CATEYE, VCG00], ["player.EquipItem {0} 0 1",
                                                   f'SetFunctionValue (($ player.GetAV Nighteye) + "|" + ($ player.GetItemCount {{0}}) + "|" + ($ {ticks().replace("{0}", "{1}")}))']),
                          "cateye 1 used", "Nighteye|count|ticks in the same script"))
    steps += [{"screenshot": "cateye1_used"}, num([], "GameDaysPassed", "cateye 1 used", "GameDaysPassed")]
    steps += sample("cateye 1 first frames Nighteye|ticks", [VCG00], ["player.GetAV Nighteye", ticks()], 10)
    steps += [until_av("Nighteye", 0, 20000), clock("cateye 1 finished"), {"screenshot": "cateye1_finished"},
              num([], "GameDaysPassed", "cateye 1 finished", "GameDaysPassed")]
    steps += sample("cateye 1 after Finish Nighteye|ticks", [VCG00], ["player.GetAV Nighteye", ticks()], 10)

    # Cateye 2 with a container menu held open 900 loops, 300 loops after the use.
    steps.append(cs.query(script([CATEYE, VCG00], ["player.EquipItem {0} 0 1",
                                                   f'SetFunctionValue (($ player.GetAV Nighteye) + "|" + ($ {ticks().replace("{0}", "{1}")}))']),
                          "cateye 2 used", "Nighteye|ticks in the same script"))
    steps += [{"screenshot": "cateye2_used"}, num([], "GameDaysPassed", "cateye 2 used", "GameDaysPassed"), {"frames": 300}]
    steps += [clock("cateye 2 menu"), {"screenshot": "cateye2_menu_open"}]
    steps += act([DRESSER], ["{0}.Activate player"], 30) + [menu(CONTAINER_MENU, "cateye 2 menu"),
                                                            num([], "player.GetAV Nighteye", "cateye 2 menu", "Nighteye")]
    steps += [{"frames": 870}, clock("cateye 2 menu", "ticks before close"), {"screenshot": "cateye2_menu_close"},
              {"console": "CloseAllMenus"}, {"frames": 5}, clock("cateye 2 menu", "ticks after close")]
    steps += [until_av("Nighteye", 0, 20000), clock("cateye 2 finished"), {"screenshot": "cateye2_finished"},
              num([], "GameDaysPassed", "cateye 2 finished", "GameDaysPassed")]

    # Cateye 3 then 4 taken 600 loops later: one Finish or two?
    steps.append(cs.query(script([CATEYE, VCG00], ["player.EquipItem {0} 0 1", f"SetFunctionValue {ticks().replace('{0}', '{1}')}"]),
                          "cateye 3 used", "ticks"))
    steps += [{"frames": 600}, num([CATEYE], "player.GetItemCount {0}", "cateye 4 before", "count")]
    steps += act([CATEYE], ["player.AddItem {0} 1 1"], 5)
    steps.append(cs.query(script([CATEYE, VCG00], ["player.EquipItem {0} 0 1",
                                                   f'SetFunctionValue (($ player.GetAV Nighteye) + "|" + ($ {ticks().replace("{0}", "{1}")}))']),
                          "cateye 4 used", "Nighteye|ticks"))
    steps += [until_av("Nighteye", 0, 20000), clock("cateye 3/4 first zero")]
    steps += act([], ["player.SetAV Nighteye 1"], 0)
    steps += [until_av("Nighteye", 0, 3000), clock("cateye 3/4 second zero")]
    steps += [num([], "player.GetAV Nighteye", "player at the end", "Nighteye"),
              num([CATEYE], "player.GetItemCount {0}", "player at the end", "cateye")]
    j = cs.job("q5c_trial_fx", "nvfdoc (uses aid items, damages the player, opens Doc's dresser; never saved).",
               steps, cs.MASTERS)
    j["title"] = "Layer 5 round 3 trial: effect scripts of aid items (about 8 min)"
    return j


def trial_order():
    """Save nvftest, travelled to Goodsprings by coc: two windows whose object scripts
    copy GetCurrentTime into `Time` every frame, against a quest script (BeatrixFX)
    that adds an hour to GameHour in its GameMode. The frame in which the windows see
    the quest's change shows whether object scripts run after quest scripts in a frame.
    Calibrated first with the job's own GameHour change. Never saved."""
    w = WINDOWS
    reads = ['({0}.GetVariable "Time")', '({1}.GetVariable "Time")', "GameHour",
             'GetVariable "reset" {2}', "GetQuestRunning {2}"]
    steps = [{"console": "coc Goodsprings"}, {"frames": 600},
             cs.query(cs.cell_query("player", (cs.MASTERS, None)), "after coc", "player cell")]
    for r in w:
        steps += [cs.query(cs.cell_query(r, (cs.MASTERS, None)), f"window {r}", "cell"),
                  num([r], "{0}.GetDisabled", f"window {r}", "disabled"),
                  num([r], '{0}.HasVariable "Time"', f"window {r}", "HasVariable"),
                  num([r], '{0}.GetVariable "Time"', f"window {r}", "Time")]
    steps += [num([], "GameHour", "clock", "GameHour"), num([], "GetCurrentTime", "clock", "GetCurrentTime"),
              num([], "TimeScale", "clock", "TimeScale")]
    steps += quest_state_beatrix("BeatrixFX at start")
    steps += sample("windows idle w1|w2|hour|reset|running", w + [BEATRIX_FX], reads, 30)
    # Calibration: the job adds an hour (at the job's point in the frame).
    steps.append(cs.query(script(w + [BEATRIX_FX], ["set GameHour to GameHour + 1",
                                                    'SetFunctionValue (' + ' + "|" + '.join(f"($ {e})" for e in reads) + ')']),
                          "job adds an hour", "w1|w2|hour|reset|running in the same script"))
    steps += sample("after the job's hour w1|w2|hour|reset|running", w + [BEATRIX_FX], reads, 20)
    # The quest adds an hour about 9 s after it starts.
    steps += act([BEATRIX_FX], ["StartQuest {0}"], 0)
    steps += sample("BeatrixFX w1|w2|hour|reset|running", w + [BEATRIX_FX], reads, 900)
    steps += quest_state_beatrix("BeatrixFX at the end")
    j = cs.job("q5c_trial_order", "nvftest (travels to Goodsprings by coc, runs BeatrixFX which changes GameHour; never saved).",
               steps, cs.MASTERS)
    j["title"] = "Layer 5 round 3 trial: quest against object scripts in one frame (about 1 min)"
    return j


def quest_state_beatrix(label):
    return [num([BEATRIX_FX], "GetQuestRunning {0}", label, "running")] + \
           [qvar(BEATRIX_FX, v, label) for v in ("reset", "bump", "timer")]


def main():
    for j in (trial_rep(), trial_fx(), trial_order()):
        path = os.path.join(HERE, f"{j['name']}.steps.json")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(json.dumps(j, indent=1) + "\n")
        print(f"{path}: {len(j['steps'])} steps")


if __name__ == "__main__":
    main()
