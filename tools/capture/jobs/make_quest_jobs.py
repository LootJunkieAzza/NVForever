#!/usr/bin/env python3
"""Writes the hand-written Layer 5 quest capture jobs (workstream 5C,
docs/spec-notes/layer5-captures.md) into this folder. The scenario jobs (state of the
intro chain, behaviour scenarios) are generated by capture_quests.py from
parity-lab/inputs/layer5/; this file keeps only the diagnostic jobs.

  python tools/capture/jobs/make_quest_jobs.py

Quest FormIDs (FalloutNV.esm, looked up read-only 2026-10-09): VCG01 0x00104C1C,
VMS22 0x00112577. No game data is stored here.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

import capture_steps as cs  # noqa: E402


def num(expr, label, field, decls=(), setup=()):
    """A query returning one number: `let fV := <expr>`."""
    return cs.query(cs.function(["float fV", *decls], [*setup, f"let fV := {expr}", "SetFunctionValue fV"]),
                    label, field)


def num_set(expr, label, field):
    """The same with the vanilla `set` statement instead of xNVSE's `let`."""
    return cs.query(cs.function(["float fV"], [f"set fV to {expr}", "SetFunctionValue fV"]), label, field)


def quest_ref(local):
    """Declarations and setup that put FalloutNV.esm's quest `local` into ref rQ."""
    return ["float fM", "ref rQ"], ['let fM := GetModIndex "FalloutNV.esm"', f"let rQ := BuildRef fM {local}"]


def trial():
    """Which ways of naming a quest and its variables the runtime compiler accepts
    (docs/spec-notes/xnvse-capture.md section 5 lists only base forms and references as
    not compiling). Read-only except two writes to VMS22 variables (no GameMode block;
    the session is never saved)."""
    d, s = quest_ref(0x104C1C)
    steps = [
        num("GetStage VCG01", "edid", "GetStage VCG01"),
        num_set("GetStage VCG01", "edid", "set GetStage VCG01"),
        num("GetStageDone VCG01 200", "edid", "GetStageDone VCG01 200"),
        num("GetQuestRunning VCG01", "edid", "GetQuestRunning VCG01"),
        num("GetQuestCompleted VCG01", "edid", "GetQuestCompleted VCG01"),
        num("GetObjectiveDisplayed VCG01 10", "edid", "GetObjectiveDisplayed VCG01 10"),
        num("GetObjectiveCompleted VCG01 10", "edid", "GetObjectiveCompleted VCG01 10"),
        num("VCG01.fTimer", "edid", "VCG01.fTimer"),
        num_set("VCG01.fTimer", "edid", "set VCG01.fTimer"),
        num("VCG01.bChooseSex", "edid", "VCG01.bChooseSex"),
        num("GetStage rQ", "ref", "GetStage rQ", d, s),
        num("GetQuestRunning rQ", "ref", "GetQuestRunning rQ", d, s),
        num('GetVariable "fTimer" rQ', "ref", "GetVariable fTimer rQ", d, s),
        num("GetStage VMS16", "edid", "GetStage VMS16"),
        num("GetQuestRunning VMQ03aTimer", "edid", "GetQuestRunning VMQ03aTimer"),
        num("ScroungerOdds", "global", "ScroungerOdds"),
        {"script": cs.function([], ["set VMS22.VMS22DinoPic to 3"], returns_value=False)},
        {"frames": cs.SETTLE_FRAMES},
        num("VMS22.VMS22DinoPic", "write", "script set VMS22.VMS22DinoPic to 3"),
        {"console": "set VMS22.VMS22DinoPic to 5"},
        {"frames": cs.SETTLE_FRAMES},
        num("VMS22.VMS22DinoPic", "write", "console set VMS22.VMS22DinoPic to 5"),
        cs.query(cs.function(["float fV"], ["let fV := 1 / 3", "SetFunctionValue ($ fV)"]), "format", "$ of 1/3"),
    ]
    j = cs.job("q5_trial", "Any save (read-only apart from two VMS22 variables; never saved).", steps, cs.MASTERS)
    j["title"] = "Layer 5 trial: quest functions and quest variables in compiled job lines (a few seconds)"
    return j


def main():
    for j in (trial(),):
        path = os.path.join(HERE, f"{j['name']}.steps.json")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(json.dumps(j, indent=1) + "\n")
        print(f"{path}: {len(j['steps'])} steps")


if __name__ == "__main__":
    main()
