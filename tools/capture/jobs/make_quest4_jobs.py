from make_quest2_jobs import num, script  # noqa: E402

VCG00 = "0x00102037"
VCG01 = "0x00104C1C"
VCG01_TEST = "0x001055BB"
CG_TUTORIAL = "0x00059C85"
VCG02 = "0x0010A214"
VCG03 = "0x0015D912"
VCG04 = "0x0011649E"
VMQ01 = "0x000842DD"
GENERIC_TIMER = "0x00168A86"
DOC = "0x00104C0F"
DOC_DOOR = "0x00103E61"
VIGOR_TESTER = "0x00104C13"
VICTOR = "0x00103DFE"
CEMETERY_MARKER = "0x001088F6"
PIPBOY = "0x00015038"
PIPBOY_GLOVE = "0x00025B83"

# MenuMode codes probed (any open menu reports its code; names are not assumed).
MENU_CODES = range(1001, 1091)


def menu_lines():
    """Lines that set fK (how many of MENU_CODES are open) and fM (the codes minus 1000,
    two digits each, in ascending order: 36 = 1036, 836 = 1008 and 1036)."""
    out = ["let fK := 0", "let fM := 0"]
    for c in MENU_CODES:
        out += [f"if MenuMode {c}", f"  let fK := fK + 1", f"  let fM := fM * 100 + {c - 1000}", "endif"]
    return out


# State lines, each one query (an expression in parentheses may not exceed 512
# characters: trial q5d_trial_open). Ref slots: {0} VCG00, {1} VCG01, {2} Doc, {3} the
# skull (stopwatch), {4} VDLCPackQuest, {5} CGTutorial; rC is the player's parent cell.
LINES = {
    "A": [("VCG00.stage", "GetStage {0}"), ("VCG00.running", "GetQuestRunning {0}"),
          ("VCG00.fTimer", 'GetVariable "fTimer" {0}'), ("VCG01.stage", "GetStage {1}"),
          ("VCG01.running", "GetQuestRunning {1}"), ("VCG01.bRunTimer", 'GetVariable "bRunTimer" {1}'),
          ("VCG01.fTimer", 'GetVariable "fTimer" {1}'), ("watch", '100000 - {3}.GetVariable "timer"')],
    "B": [("menu", "MenuMode"), ("menus.n", "fK"), ("menus", "fM"), ("GameHour", "GameHour"),
          ("x", "player.GetPos X"), ("y", "player.GetPos Y"), ("z", "player.GetPos Z"), ("doc.talking", "{2}.IsTalking")],
    "C": [("packs.given", 'GetVariable "nGiven" {4}'), ("CGTutorial.stage", "GetStage {5}"),
          ("controls.any", "GetPlayerControlsDisabled"), ("objective10", "GetObjectiveDisplayed {1} 10"),
          ("VCG01.bChooseSex", 'GetVariable "bChooseSex" {1}'), ("VCG01.done.200", "GetStageDone {1} 200")],
}
LINE_NAMES = [VCG00, VCG01, DOC, "0x00104C10", "0x0017912D", CG_TUTORIAL]


def line_query(name, label, field):
    exprs = LINES[name]
    body = (menu_lines() if name == "B" else []) + (["let rC := player.GetParentCell"] if name == "B" else [])
    tail = ' + "|" + (GetFormIDString rC)' if name == "B" else ""
    body += ["SetFunctionValue (" + ' + "|" + '.join(f"($ ({e}))" for _, e in exprs) + tail + ")"]
    return cs.query(script(LINE_NAMES, body, ("float fK", "float fM", "ref rC")), f"{label}:{name}", field)


def samples(label, n, shot_every=0):
    """n samples, each the three state lines in three game loops."""
    out = []
    for k in range(n):
        if shot_every and k % shot_every == 0:
            out.append({"screenshot": f"{label.replace(' ', '_')}_{k:05d}"})
        out += [line_query(x, f"sample:{label}", str(k)) for x in "ABC"]
    return out


def watch_start():
    """The stopwatch: the skull in Doc's house (VCG01BrahminSkullSCRIPT counts `timer`
    down by GetSecondsPassed in GameMode while runTimer is 1; with grabbed 0 nothing
    happens when it runs out; layer5-captures.md section 8.3 d)."""
    return [{"script": script(["0x00104C10"], ['{0}.SetVariable "timer" 100000', '{0}.SetVariable "runTimer" 1',
                                                "SetFunctionValue 1"])}, {"frames": 2}]


def probes(label):
    """One query per function whose compile and value the drive jobs need."""
    steps = [num([], f"GetPlayerControlsDisabled {' '.join('1' if j == k else '0' for j in range(7))}", label,
                 f"controls.{k}") for k in range(7)]
    steps += [num([], "GetPlayerControlsDisabled", label, "controls.any"),
              num([DOC_DOOR], "{0}.GetDestroyed", label, "door.destroyed"),
              num([VIGOR_TESTER], "{0}.GetDestroyed", label, "tester.destroyed"),
              num([VICTOR], "{0}.GetDisabled", label, "victor.disabled"),
              num([PIPBOY], "player.GetItemCount {0}", label, "pipboy"),
              num([PIPBOY_GLOVE], "player.GetItemCount {0}", label, "pipboy glove"),
              num([], "player.GetIsSex Male", label, "male"),
              num([], "IsPlayerTagSkill Guns", label, "tag.Guns"),
              num([DOC], "{0}.GetDistance player", label, "doc.distance"),
              num([], "TimeScale", label, "TimeScale"),
              num([], "GameDaysPassed", label, "GameDaysPassed"),
              cs.query(script([], ["let fN := 1036", "let fV := MenuMode fN", "SetFunctionValue fV"],
                              ("float fN", "float fV")), label, "MenuMode variable"),
              cs.query(script([], ["let rP := player.GetCurrentPackage", "SetFunctionValue (GetFormIDString rP)"],
                              ("ref rP",)), label, "player package"),
              cs.query(script([DOC], ["let rP := {0}.GetCurrentPackage", "SetFunctionValue (GetFormIDString rP)"],
                              ("ref rP",)), label, "doc package")]
    return steps


def pack_state(label):
    names = ["bClassicItemsGiven", "bCaravanItemsGiven", "bMercenaryItemsGiven", "bTribalItemsGiven",
             "bClassicInstalledOnce", "bCaravanInstalledOnce", "bMercenaryInstalledOnce", "bTribalInstalledOnce", "nGiven"]
    steps = [num(["0x0017912D"], f'GetVariable "{v}" {{0}}', label, v) for v in names]
    steps += [num([q], "GetQuestRunning {0}", label, f"running {q}") for q in PACK_QUESTS]
    return steps


PACK_QUESTS = ["0x00172A1F", "0x00172A1E", "0x001674D4", "0x00172A1D", "0x00174095"]


def trial_open():
    """Save nvfnew: the pack plugins' message boxes are open at load (trial
    q5d_trial_open's screenshots). State lines every 3 loops: 150 samples without input,
    then four rounds of the Enter key (xNVSE TapKey 28, the player pressing OK) with 60
    samples each, 300 samples, four rounds of the console's CloseAllMenus with 60 samples
    each, and 900 samples. Screenshots after every input. Never saved."""
    steps = pack_state("packs at load") + probes("probes at load") + watch_start()
    steps += samples("open", 150, 50)
    for r in range(4):
        steps += [{"script": script([], ["TapKey 28", "SetFunctionValue 1"])}, {"frames": 3},
                  {"screenshot": f"tapkey_{r}"}]
        steps += samples(f"after TapKey {r}", 60, 30)
    steps += pack_state("packs after TapKey") + samples("after the keys", 300, 50)
    for r in range(4):
        steps += [{"console": "CloseAllMenus"}, {"frames": 3}, {"screenshot": f"closeallmenus_{r}"}]
        steps += samples(f"after CloseAllMenus {r}", 60, 30)
    steps += pack_state("packs after CloseAllMenus") + samples("run", 900, 50)
    steps += probes("probes at the end") + pack_state("packs at the end")
    j = cs.job("q5d_trial_open", "nvfnew (presses Enter and closes menus; never saved).", steps, cs.MASTERS)
    j["title"] = "Layer 5 round 4 trial: the opening of a new game, pack messages dismissed (about 3 min)"
    return j


def until(lines, max_frames):
    """Polls once per game loop until the lines set fV (slots as LINE_NAMES)."""
    return {"until": script(LINE_NAMES, ["let fV := 0"] + lines + ["SetFunctionValue fV"]), "max_frames": max_frames}


def cond(expr):
    return [f"if {expr}", "  let fV := 1", "endif"]


def at(label, shot=False):
    """The three state lines once (3 loops), after a wait; optional screenshot."""
    out = [{"screenshot": label.replace(" ", "_")}] if shot else []
    return out + [line_query(x, f"at:{label}", "0") for x in "ABC"]


def wait_done(quest_slot, stage, max_frames=2400, shot=False, name=None):
    q = "{%d}" % quest_slot
    return [until(cond(f"GetStageDone {q} {stage}"), max_frames)] + at(name or f"{['VCG00', 'VCG01'][quest_slot]} {stage}", shot)


def wait_menu(code, label, max_frames=2400):
    return [until(cond(f"MenuMode {code}"), max_frames)] + at(label, True)


def close(label):
    return [{"console": "CloseAllMenus"}, {"frames": 3}] + at(label, True)


def dismiss_boxes(label, n, max_frames=900):
    out = []
    for k in range(n):
        out += wait_menu(1001, f"{label} box {k}", max_frames) + close(f"{label} box {k} closed")
    return out


def trial_drive1():
    """Save nvfnew, driven: the pack message boxes are closed as they open (console
    CloseAllMenus), then each stage of VCG00/VCG01 is waited for (GetStageDone, polled
    every loop) and the state lines read once; menus are waited for and closed; stage 60
    (the vigor tester trigger's SetStage) is set by the job, the tester is activated
    with its OnActivate block. Never saved."""
    steps = watch_start() + at("load", True) + dismiss_boxes("packs", 4)
    for s in (95, 100):
        steps += wait_done(0, s)
    for s in (0, 1, 3, 5, 7, 8):
        steps += wait_done(1, s)
    steps += wait_done(1, 10, shot=True) + wait_menu(1051, "name menu")
    steps += samples("in the name menu", 20) + close("name menu closed") + samples("after the name menu", 100)
    for s in (15, 25, 30, 35):
        steps += wait_done(1, s, shot=True)
    steps += wait_done(1, 36, shot=True) + wait_menu(1036, "race menu") + samples("in the race menu", 40)
    steps += close("race menu closed") + samples("after the race menu", 60)
    for s in (40, 45, 50):
        steps += wait_done(1, s, shot=True)
    steps += wait_done(1, 55, shot=True) + dismiss_boxes("tutorial", 3, 600) + samples("after 55", 200, 50)
    steps += probes("probes at 55")
    steps += [{"script": script(LINE_NAMES, ["SetStage {1} 60", "SetFunctionValue 1"])}, {"frames": 3}]
    steps += wait_done(1, 60, shot=True)
    steps += [until(cond("GetObjectiveDisplayed {1} 30"), 2400)] + at("objective 30 shown", True)
    steps += samples("before the tester", 100, 50)
    steps += [{"script": script([VIGOR_TESTER], ["{0}.Activate player 1", "SetFunctionValue 1"])}, {"frames": 30}]
    steps += at("tester activated", True) + samples("tester menu", 40, 20) + close("tester menu closed")
    for s in (65, 70, 75, 76, 79, 80):
        steps += wait_done(1, s, shot=True)
    steps += samples("after 80", 300, 50) + probes("probes at the end")
    j = cs.job("q5d_trial_drive1", "nvfnew (closes menus, sets VCG01 60, activates the vigor tester; never saved).",
               steps, cs.MASTERS)
    j["title"] = "Layer 5 round 4 trial: VCG01 driven from the opening to stage 80 (about 4 min)"
    return j


SKILLS = ["Barter", "EnergyWeapons", "Explosives", "Guns", "Lockpick", "Medicine", "MeleeWeapons", "Repair",
          "Science", "Sneak", "Speech", "Survival", "Unarmed"]
VCG01_VARS = ["bChooseSex", "nButton", "bRunTimer", "bGiveTest", "fTimer", "bBeganTest", "nDocReaction",
              "nMostExtremeStat", "bLow", "fMaxDeviation", "fCurrentValue", "fAbsCurrentValue"]
TEST_VARS = ["nMaxStatValue", "nBestSpecialStat", "nSpecialBias", "nBarter", "nBigGuns", "nEnergyWeapons", "nExplosives",
             "nLockpick", "nMedicine", "nMelee", "nRepair", "nScience", "nSmallGuns", "nSneak", "nSpeech", "nSurvival",
             "nUnarmed", "nTopCombat", "nTopGateOpener", "nTopOverall", "nSkillsLeftToBeat", "nSneakBias",
             "bApplySneakBias", "nMaxValue", "bDoFinalCalculation"]


def quest_reads(quest, label, stages=(), objectives=(), vars_=()):
    steps = [num([quest], "GetQuestRunning {0}", label, "running"), num([quest], "GetQuestCompleted {0}", label, "completed"),
             num([quest], "GetStage {0}", label, "stage")]
    steps += [num([quest], f"GetStageDone {{0}} {s}", label, f"done.{s}") for s in stages]
    for o in objectives:
        steps += [num([quest], f"GetObjectiveDisplayed {{0}} {o}", label, f"objective.{o}.displayed"),
                  num([quest], f"GetObjectiveCompleted {{0}} {o}", label, f"objective.{o}.completed")]
    steps += [num([quest], f'GetVariable "{v}" {{0}}', label, f"var.{v}") for v in vars_]
    return steps


def job_script(names, lines, settle=3):
    return [{"script": script(names, list(lines) + ["SetFunctionValue 1"])}, {"frames": settle}]


def until_var(quest, var, value, max_frames):
    return {"until": script([quest], ["let fV := 0", f'if GetVariable "{var}" {{0}} == {value}', "  let fV := 1",
                                      "endif", "SetFunctionValue fV"]), "max_frames": max_frames}


def trial_drive2():
    """Save nvfnew, the later part of VCG01 reached without passing stage 55 (whose
    result script autosaves: trial q5d_trial_drive1 wrote autosave.fos). While the pack
    message box still holds GameMode the job sets VCG01 0 and 60 and shows objective 30
    (the effect of Doc's line at 60 in the natural order), then closes the boxes; the
    vigor tester (OnActivate), Doc's reaction (65-80), the psych test's effect
    (VCG01Test scores, bDoFinalCalculation 1), 85-110 with their menus closed, 115 (the
    exit trigger's SetStage), the farewell dialogue's effects (Pip-Boy, VGenericTimer
    event 3) and 200 with VMQ01, VCG02 and VCG04. Never saved."""
    v1 = VCG01
    steps = watch_start() + at("load", True)
    steps += job_script([v1], ["SetStage {0} 0"]) + at("set 0")
    steps += job_script([v1], ["SetStage {0} 60"]) + at("set 60")
    steps += job_script([v1], ["SetObjectiveDisplayed {0} 30 1"]) + at("objective 30 shown")
    steps += dismiss_boxes("packs", 4)
    steps += samples("after the boxes", 200, 50)
    steps += quest_reads(v1, "VCG01 before the tester", (0, 1, 3, 5, 7, 8, 10, 55, 60), (10, 30), VCG01_VARS)
    same = 'SetFunctionValue (($ GetStage {1}) + "|" + ($ GetObjectiveCompleted {1} 30) + "|" + ($ {0}.GetDestroyed))'
    steps += [cs.query(script([VIGOR_TESTER, v1], ["{0}.Activate player 1", same]),
                       "tester activated", "stage|objective 30 completed|destroyed in the same script"), {"frames": 30}]
    steps += at("tester menu", True) + close("tester menu closed")
    for s in (70, 75, 76, 79, 80):
        steps += wait_done(1, s, shot=True)
    steps += quest_reads(v1, "VCG01 at 80", (60, 65, 70, 75, 76, 78, 79, 80), (10, 30, 40), VCG01_VARS)
    steps += [num([VIGOR_TESTER], "{0}.GetDestroyed", "VCG01 at 80", "tester destroyed")]
    # The psych test: the answers' result scripts add to VCG01Test's scores; the last one
    # sets bDoFinalCalculation 1 and VCG01 85 (INFO 0x00105570 and others).
    scores = {"nSneak": 2, "nScience": 3, "nSpeech": 1, "nSmallGuns": 2, "nMedicine": 1, "nSurvival": 1}
    steps += quest_reads(VCG01_TEST, "VCG01Test before", (), (), TEST_VARS)
    steps += [num([], f"IsPlayerTagSkill {s}", "tag skills before", s) for s in SKILLS]
    steps += job_script([v1, VCG01_TEST], ['SetVariable "bBeganTest" 1 {0}', 'SetVariable "bGiveTest" 0 {0}',
                                           "SetObjectiveCompleted {0} 40 1"]
                        + [f'SetVariable "{k}" {v} {{1}}' for k, v in scores.items()]
                        + ['SetVariable "bDoFinalCalculation" 1 {1}'])
    steps += [until_var(VCG01_TEST, "bDoFinalCalculation", 2, 600)]
    steps += quest_reads(VCG01_TEST, "VCG01Test after", (), (), TEST_VARS)
    steps += [num([], f"IsPlayerTagSkill {s}", "tag skills after", s) for s in SKILLS]
    steps += job_script([v1], ["SetStage {0} 85"]) + at("set 85", True)
    steps += wait_done(1, 90, shot=True) + samples("tag skill menu", 30, 15) + close("tag skill menu closed")
    for s in (95, 98, 100):
        steps += wait_done(1, s, shot=True)
    steps += wait_done(1, 102, shot=True) + samples("trait menu", 30, 15) + close("trait menu closed")
    for s in (105, 110):
        steps += wait_done(1, s, 2400, shot=True)
    steps += quest_reads(v1, "VCG01 at 110", (85, 90, 95, 98, 100, 102, 105, 110), (40, 50), VCG01_VARS)
    steps += [num([], f"IsPlayerTagSkill {s}", "tag skills at 110", s) for s in SKILLS]
    steps += probes("probes at 110")
    steps += job_script([v1], ["SetStage {0} 115"]) + at("set 115", True)
    steps += samples("Doc to the exit", 300, 50)
    steps += [until(cond("MenuMode 1009"), 1800)] + at("dialogue", True) + close("dialogue closed")
    # The farewell dialogue's result scripts (INFO 0x001057E4, 0x001057E7) without the
    # message boxes: Pip-Boy, controls, VGenericTimer event 3 in 0.1 s.
    steps += job_script([PIPBOY, PIPBOY_GLOVE], ["player.AddItem {0} 1", "player.AddItem {1} 1", "player.EquipItem {0}",
                                                 "player.EquipItem {1}"], 30)
    steps += job_script([GENERIC_TIMER], ["EnablePlayerControls 1 1 0 1 1 1 0", 'SetVariable "fTimer" 0.1 {0}',
                                          'SetVariable "nEvent" 3 {0}', "StartQuest {0}"])
    steps += wait_done(1, 200, 1200, shot=True)
    steps += samples("after 200", 100, 50)
    steps += quest_reads(v1, "VCG01 at the end", (110, 115, 200), (10, 30, 40, 50), ("bRunTimer", "fTimer"))
    steps += quest_reads(VMQ01, "VMQ01 at the end", (10, 15), (10, 20, 25, 30))
    steps += quest_reads(VCG02, "VCG02 at the end", (5, 10), (3, 5, 10))
    steps += quest_reads(VCG04, "VCG04 at the end", (), (), ("Initialized", "Done", "bActivated"))
    steps += quest_reads(GENERIC_TIMER, "VGenericTimer at the end", (), (), ("nEvent", "fTimer"))
    steps += [num([CEMETERY_MARKER], "{0}.GetDisabled", "at the end", "cemetery marker disabled"),
              num([], "GameHour", "at the end", "GameHour"),
              num([PIPBOY], "player.GetItemCount {0}", "at the end", "pipboy"),
              num([PIPBOY], "player.GetEquipped {0}", "at the end", "pipboy equipped")]
    steps += probes("probes at the end")
    j = cs.job("q5d_trial_drive2", "nvfnew (sets VCG01 stages from 60 on, never 55; closes menus; never saved).",
               steps, cs.MASTERS)
    j["title"] = "Layer 5 round 4 trial: VCG01 60 to 200 without stage 55 (about 5 min)"
    return j


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description="round 4 trial jobs (large: written outside the repository)")
    ap.add_argument("-o", "--out-dir", default="C:/fnv-private/capture/quest4")
    args = ap.parse_args(argv)
    os.makedirs(args.out_dir, exist_ok=True)
    for j in (trial_open(), trial_drive1(), trial_drive2()):
        path = os.path.join(args.out_dir, f"{j['name']}.steps.json")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(json.dumps(j, indent=1) + "\n")
        print(f"{path}: {len(j['steps'])} steps")


if __name__ == "__main__":
    main()
