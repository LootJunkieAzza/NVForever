"""Writes the diagnostic jobs of the fourth round of Layer 5 captures (workstream 5C,
docs/spec-notes/layer5-captures.md section 10: the intro quest VCG01 from the owner's
new-game save `nvfnew`) (see below for where). Scenario jobs are generated by
capture_quests.py from parity-lab/inputs/layer5/intro_*.actions.json; these jobs only find
out what can be observed and how.

  python tools/capture/jobs/make_quest4_jobs.py [-o C:/fnv-private/capture/quest4]

The trial jobs are 6-16 MB each (every state sample carries the menu scan), so they are
written outside the repository (default C:/fnv-private/capture/quest4) and run from
there with capture_run.py; they hold no game data.

Forms (FalloutNV.esm FormIDs, looked up read-only 2026-10-09 with `fnvtool esm decode`
and the masters' script sources; no game data is stored here):
- quests VCG00 0x00102037 (opening; quest script counts fTimer down while bRunTimer is 1
  and moves to the next stage when it runs out), VCG01 0x00104C1C (the intro), VCG01Test
  0x001055BB (psych test scores), CGTutorial 0x00059C85, VCG02 0x0010A214, VCG03
  0x0015D912, VCG04 0x0011649E, VMQ01 0x000842DD, VGenericTimer 0x00168A86;
- references DocMitchellREF 0x00104C0F, GSDocMitchellHouseIntDoorREF 0x00103E61 (set
  destroyed by VCG01 stage 0), VCG01VigorTesterREF 0x00104C13 (set destroyed by stage 65),
  VictorREF 0x00103DFE (disabled by VCG01 stage 0), GoodspringsCemeteryMapMarker
  0x001088F6 (enabled by VMQ01 stage 10);
- items Pipboy 0x00015038, PipboyGlove 0x00025B83.
"""
