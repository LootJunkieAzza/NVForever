//! Starts from Mod Organizer 2: its profile's plugins, not NVForever's own list
//! (owner request 2026-10-18; docs/mod-organizer-2.md).
//!
//! Mod Organizer 2 (MO2) starts a program with its file system hook, usvfs, injected
//! [documented: MO2 source, `OrganizerCore::beforeRun`/`fileMapping`]. The hook shows the
//! program the game's `Data` folder with the active mods' files merged into it, and puts
//! the profile's `plugins.txt` and `loadorder.txt` at
//! `<Local AppData>\<game short name>\` [documented: `GameGamebryo::mappings` in
//! modorganizer-game_gamebryo; for New Vegas that is `%LOCALAPPDATA%\FalloutNV`]. So a
//! program MO2 started reads MO2's list at the original game's path, while every other
//! program sees the game's own file there.
//!
//! MO2's `plugins.txt` [documented: `GamebryoGamePlugins::writeList`]:
//! - first line `# This file was automatically generated by Mod Organizer.`;
//! - then the active plugins only, one per line, sorted by MO2's priority (the right
//!   pane's order), lines ending in CRLF;
//! - written in the system's ANSI code page (its `loadorder.txt` is UTF-8).
//!
//! NVForever takes MO2's list only when both hold: the hook's DLL is loaded in this process
//! ([`usvfs_loaded`]; `usvfs_x64.dll` [documented: usvfs `src/usvfs_dll/CMakeLists.txt`,
//! name `usvfs` + `_x64` on 64-bit]), and the file there starts with MO2's header line. The
//! header guard means a hook without MO2's mapping (another game's instance, say) reads
//! the original game's own list, which is then not used.

use crate::plugins::{data_plugins, PluginEntry, PluginList, PluginSync};
use crate::{GameInstall, InstallError};
use std::path::PathBuf;

/// The first line MO2 writes in the lists it makes.
pub const HEADER: &str = "# This file was automatically generated by Mod Organizer.";

/// The usvfs DLL MO2 injects into a 64-bit program.
pub const USVFS_DLL: &str = "usvfs_x64.dll";

/// Whether usvfs is loaded in this process, i.e. MO2 (or another usvfs user) started it.
#[cfg(windows)]
pub fn usvfs_loaded() -> bool {
    #[link(name = "kernel32")]
    extern "system" {
        fn GetModuleHandleW(name: *const u16) -> *mut core::ffi::c_void;
    }
    let name: Vec<u16> = USVFS_DLL.encode_utf16().chain(std::iter::once(0)).collect();
    // SAFETY: a NUL-terminated UTF-16 name; GetModuleHandleW takes no reference and the
    // handle is only compared with null.
    !unsafe { GetModuleHandleW(name.as_ptr()) }.is_null()
}

#[cfg(not(windows))]
pub fn usvfs_loaded() -> bool {
    false
}

/// Where MO2 puts its profile's `plugins.txt` for New Vegas: the Local AppData known
/// folder (`directories` reads the same known folder MO2 does), `FalloutNV\plugins.txt`.
pub fn plugins_file() -> Option<PathBuf> {
    directories::BaseDirs::new().map(|d| d.data_local_dir().join("FalloutNV").join("plugins.txt"))
}

/// The plugins of an MO2 `plugins.txt` in order, or `None` when the file is not MO2's (no
/// header line). Bytes that are not UTF-8 are read as Windows-1252's Latin-1 subset
/// [hypothesis: the ANSI code page of a Western-language Windows; other code pages would
/// mis-read non-ASCII names, which then show as missing].
pub fn parse(bytes: &[u8]) -> Option<Vec<String>> {
    let text = match std::str::from_utf8(bytes) {
        Ok(t) => t.to_string(),
        Err(_) => bytes.iter().map(|&b| b as char).collect(),
    };
    let text = text.strip_prefix('\u{feff}').unwrap_or(&text);
    let mut lines = text.lines();
    if lines.next()?.trim() != HEADER {
        return None;
    }
    let mut names: Vec<String> = Vec::new();
    for line in lines {
        let t = line.trim();
        if t.is_empty() || t.starts_with('#') {
            continue;
        }
        // Later games' lists mark active plugins with `*`; New Vegas' has none, but the
        // star is never part of a file name.
        let name = t.strip_prefix('*').unwrap_or(t).trim();
        if !name.is_empty() && !names.iter().any(|n| n.eq_ignore_ascii_case(name)) {
            names.push(name.to_string());
        }
    }
    Some(names)
}

/// What to load from MO2's list: its plugins present in `Data` (MO2's merged one), in its
/// order, `FalloutNV.esm` first. `None` when this start is not from MO2 or the file there
/// is not MO2's. NVForever's own list is neither read nor written.
pub fn sync(game: &GameInstall) -> Result<Option<(PathBuf, PluginSync)>, InstallError> {
    if !usvfs_loaded() {
        return Ok(None);
    }
    let Some(path) = plugins_file() else { return Ok(None) };
    let bytes = match std::fs::read(&path) {
        Ok(b) => b,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(e) => return Err(InstallError::Io(path, e)),
    };
    let Some(names) = parse(&bytes) else { return Ok(None) };
    Ok(Some((path, load(&names, &data_plugins(game)?))))
}

/// MO2's active `names` against the plugins `present` in `Data`.
fn load(names: &[String], present: &[String]) -> PluginSync {
    let list = PluginList { entries: names.iter().map(|n| PluginEntry { name: n.clone(), active: true }).collect() };
    let (load, missing, base_forced) = list.load_order(present);
    PluginSync { load, added: Vec::new(), missing, base_forced, written: false }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn names(v: &[&str]) -> Vec<String> {
        v.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn reads_mo2_list_in_its_order() {
        let text = format!("{HEADER}\r\nFalloutNV.esm\r\nDeadMoney.esm\r\nYUP - Base Game + All DLC.esm\r\nMod.esp\r\n");
        let n = parse(text.as_bytes()).unwrap();
        assert_eq!(n, names(&["FalloutNV.esm", "DeadMoney.esm", "YUP - Base Game + All DLC.esm", "Mod.esp"]));
        let present = names(&["FalloutNV.esm", "DeadMoney.esm", "mod.esp", "Off.esp", "YUP - Base Game + All DLC.esm"]);
        let s = load(&n, &present);
        // Named as in Data; plugins MO2 left off (Off.esp) are not loaded.
        assert_eq!(s.load, names(&["FalloutNV.esm", "DeadMoney.esm", "YUP - Base Game + All DLC.esm", "mod.esp"]));
        assert!(s.missing.is_empty() && !s.base_forced && !s.written);
    }

    #[test]
    fn not_mo2_without_its_header() {
        // The original game's own list: plain names, no header.
        assert_eq!(parse(b"FalloutNV.esm\r\nDeadMoney.esm\r\n"), None);
        assert_eq!(parse(b""), None);
    }

    #[test]
    fn missing_plugins_and_base_first() {
        let text = format!("{HEADER}\r\nMod.esp\r\nFalloutNV.esm\r\nGone.esp\r\n");
        let s = load(&parse(text.as_bytes()).unwrap(), &names(&["FalloutNV.esm", "Mod.esp"]));
        assert_eq!(s.load, names(&["FalloutNV.esm", "Mod.esp"]));
        assert_eq!(s.missing, names(&["Gone.esp"]));
        assert!(s.base_forced);
    }

    #[test]
    fn ansi_names_and_stars() {
        let mut bytes = format!("{HEADER}\r\n*FalloutNV.esm\r\n").into_bytes();
        bytes.extend_from_slice(b"Caf\xe9.esp\r\n");
        assert_eq!(parse(&bytes).unwrap(), names(&["FalloutNV.esm", "Caf\u{e9}.esp"]));
    }

    #[test]
    fn not_under_mo2_in_tests() {
        assert!(!usvfs_loaded());
    }
}
