    #[test]
    fn save_goes_to_the_owning_mod_else_overwrite() {
        let t = std::env::temp_dir().join(format!("nvf-mo2-save-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&t);
        let l = Layout { mods: t.join("mods"), overwrite: t.join("overwrite"), profile: t.join("profiles/P") };
        for d in [l.mods.join("Top"), l.mods.join("Low"), l.mods.join("Off"), l.overwrite.clone(), l.profile.clone()] {
            std::fs::create_dir_all(d).unwrap();
        }
        std::fs::write(l.profile.join("modlist.txt"), format!("{HEADER}\r\n+Top\r\n-Off\r\n+Low\r\n")).unwrap();
        std::fs::write(l.mods.join("Low/Both.esp"), "").unwrap();
        std::fs::write(l.mods.join("Top/both.ESP"), "").unwrap();
        std::fs::write(l.mods.join("Low/Mine.esp"), "").unwrap();
        std::fs::write(l.mods.join("Off/Hidden.esp"), "").unwrap();
        // The highest enabled mod with the file, matched without case.
        let s = l.save_target("Both.esp");
        assert_eq!((s.mod_name.as_deref(), s.exists), (Some("Top"), true));
        assert!(s.path.ends_with("both.ESP"), "{}", s.path.display());
        assert_eq!(l.save_target("Mine.esp").mod_name.as_deref(), Some("Low"));
        // A disabled mod's file and a new name go to overwrite.
        for n in ["Hidden.esp", "New.esp"] {
            assert_eq!(l.save_target(n), SaveTarget { path: l.overwrite.join(n), mod_name: None, exists: false });
        }
        // Overwrite beats every mod.
        std::fs::write(l.overwrite.join("Mine.esp"), "").unwrap();
        assert_eq!(l.save_target("Mine.esp"), SaveTarget { path: l.overwrite.join("Mine.esp"), mod_name: None, exists: true });
        std::fs::remove_dir_all(&t).ok();
    }

    #[test]
    fn turn_on_in_the_profile() {
        let t = std::env::temp_dir().join(format!("nvf-mo2-on-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&t);
        let l = Layout { mods: t.join("mods"), overwrite: t.join("overwrite"), profile: t.join("P") };
        std::fs::create_dir_all(&l.profile).unwrap();
        std::fs::write(l.profile.join("plugins.txt"), format!("{HEADER}\r\nFalloutNV.esm")).unwrap();
        std::fs::write(l.profile.join("loadorder.txt"), format!("{HEADER}\r\nFalloutNV.esm\r\nOff.esp\r\n")).unwrap();
        assert!(l.turn_on("Caf\u{e9}.esp").unwrap());
        let p = std::fs::read(l.profile.join("plugins.txt")).unwrap();
        assert!(p.ends_with(b"FalloutNV.esm\r\nCaf\xe9.esp\r\n"));
        assert_eq!(parse(&p).unwrap(), names(&["FalloutNV.esm", "Caf\u{e9}.esp"]));
        let o = std::fs::read_to_string(l.profile.join("loadorder.txt")).unwrap();
        assert!(o.ends_with("Off.esp\r\nCaf\u{e9}.esp\r\n"));
        // Again: already on, nothing written twice.
        assert!(!l.turn_on("caf\u{e9}.ESP").unwrap());
        assert_eq!(std::fs::read(l.profile.join("plugins.txt")).unwrap(), p);
        std::fs::remove_dir_all(&t).ok();
    }

    /// A game folder outside ASCII, as Qt escapes it in a `@ByteArray`: the bytes of its
    /// UTF-8 as `\xNN` (Cyrillic `Игры`, accented `José`); a digit after an escape is
    /// escaped too; the one-letter escapes; a plain value's `\x` is a character [#1996].
    #[test]
    fn game_path_escapes_outside_ascii() {
        let cyr = "[General]\ngamePath=@ByteArray(D:\\\\\\xd0\\x98\\xd0\\xb3\\xd1\\x80\\xd1\\x8b\\\\Fallout New Vegas)\n";
        assert_eq!(ini_game_path(cyr), Some(PathBuf::from("D:\\Игры\\Fallout New Vegas")));
        let acc = "[General]\ngamePath=@ByteArray(C:\\\\Users\\\\Jos\\xc3\\xa9\\\\FNV)\n";
        assert_eq!(ini_game_path(acc), Some(PathBuf::from("C:\\Users\\José\\FNV")));
        // `é2`: the 2 after the escape is escaped as well, so the hex run ends at it.
        assert_eq!(qt_unescape("Jos\\xc3\\xa9\\x32\\\"\\t", true), "José2\"\t");
        // Bytes that are not UTF-8 read as Latin-1.
        assert_eq!(qt_unescape("Jos\\xe9", true), "José");
        assert_eq!(qt_unescape("Jos\\xe9 \\0101", false), "José A");
    }

    #[test]
    fn instance_chosen_as_mo2_does() {
        let t = std::env::temp_dir().join(format!("nvf-mo2-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&t);
        let (app, global) = (t.join("MO2"), t.join("global"));
        std::fs::create_dir_all(&app).unwrap();
        // No portable INI and no current instance: none.
        assert_eq!(pick_instance(&app, "", Some(&global)), None);
        std::fs::write(app.join("ModOrganizer.ini"), "").unwrap();
        assert_eq!(pick_instance(&app, "", Some(&global)), Some(app.clone()));
        // A current global instance wins over the portable INI ...
        assert_eq!(pick_instance(&app, "Viva", Some(&global)), Some(global.join("Viva")));
        // ... unless portable.txt locks MO2 to its portable instance.
        std::fs::write(app.join("portable.txt"), "").unwrap();
        assert_eq!(pick_instance(&app, "Viva", Some(&global)), Some(app.clone()));
        std::fs::remove_dir_all(&t).ok();
    }
