/// [documented: GetKeyName] the name of a key or mouse button code.
pub fn key_name(code: i64) -> &'static str {
    u16::try_from(code).ok().and_then(|c| KEY_NAMES.iter().find(|(k, _)| *k == c)).map_or("<no key>", |(_, n)| n)
}
